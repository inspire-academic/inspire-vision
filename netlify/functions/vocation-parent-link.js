// Creates (or returns the existing) token-gated parent access link for a
// Vocation & Life Pathways journey. Callable by the mentee themselves (for
// their own journey) or by their assigned mentor — both are verified
// server-side from the caller's own Supabase session, never trusted from
// the request body. Same double-client pattern as notify-mentor-message.js:
// an anon client verifies who's calling, a service-role client does the
// actual write (RLS on vocation_parent_links has zero client policies by
// design — a parent has no auth.users identity for RLS to check against,
// so this function is the only path that can ever create a row).
//
// The access_token itself is generated by the table's own DEFAULT
// (encode(gen_random_bytes(24),'hex')) — this function never invents or
// receives one from the client. No expiry is set by default (expires_at
// stays null); revocation is a manual follow-up, not built here (see
// IMPLEMENTATION_PLAN.md's MVP cut lines).
const { Resend } = require('resend');
const { createClient } = require('@supabase/supabase-js');
const { getAdminClient } = require('./_lib/adminAuth');

const SUPABASE_URL = 'https://ygtsrdwoikqnrbexjrtl.supabase.co';
const SUPABASE_ANON_KEY = 'sb_publishable_XxmrO4J18iyQ1Srub73BhQ_FBhd8mXR';

exports.handler = async (event) => {
  if (event.httpMethod !== 'POST') {
    return { statusCode: 405, body: 'Method Not Allowed' };
  }

  const authHeader = event.headers.authorization || event.headers.Authorization || '';
  const token = authHeader.replace(/^Bearer\s+/i, '');
  if (!token) {
    return { statusCode: 401, body: JSON.stringify({ error: 'Missing Authorization header' }) };
  }
  const anon = createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
  const { data: { user: caller }, error: authErr } = await anon.auth.getUser(token);
  if (authErr || !caller) {
    return { statusCode: 401, body: JSON.stringify({ error: 'Invalid or expired session' }) };
  }

  if (!process.env.SUPABASE_SERVICE_ROLE_KEY) {
    return { statusCode: 200, body: JSON.stringify({ error: 'Not configured — SUPABASE_SERVICE_ROLE_KEY missing' }) };
  }

  let studentId, parentEmail;
  try {
    ({ studentId, parentEmail } = JSON.parse(event.body || '{}'));
  } catch (e) {
    return { statusCode: 400, body: JSON.stringify({ error: 'Invalid JSON body' }) };
  }
  studentId = studentId || caller.id;

  try {
    const admin = getAdminClient();

    // Authorize: caller must be the student themselves, or their active
    // assigned mentor. Re-derived server-side — never trust studentId
    // alone as proof of authorization.
    if (studentId !== caller.id) {
      const { data: assignment } = await admin.schema('mentorship').from('mentor_assignments')
        .select('id').eq('mentor_id', caller.id).eq('student_id', studentId).eq('status', 'active').maybeSingle();
      if (!assignment) {
        return { statusCode: 403, body: JSON.stringify({ error: 'Not authorized for this student' }) };
      }
    }

    // Reuse an existing non-revoked link if one already exists, rather
    // than minting a new token (and invalidating any link already shared)
    // every time this is called.
    const { data: existing, error: existingErr } = await admin.schema('mentorship').from('vocation_parent_links')
      .select('*').eq('student_id', studentId).is('revoked_at', null).order('created_at', { ascending: false }).limit(1).maybeSingle();
    if (existingErr) throw existingErr;

    let link = existing;
    if (!link) {
      const { data: created, error: createErr } = await admin.schema('mentorship').from('vocation_parent_links')
        .insert({ student_id: studentId, parent_email: parentEmail || null, created_by: caller.id })
        .select().single();
      if (createErr) throw createErr;
      link = created;
    } else if (parentEmail && parentEmail !== link.parent_email) {
      const { data: updated, error: updateErr } = await admin.schema('mentorship').from('vocation_parent_links')
        .update({ parent_email: parentEmail }).eq('id', link.id).select().single();
      if (updateErr) throw updateErr;
      link = updated;
    }

    const host = event.headers['x-forwarded-host'] || event.headers.host;
    const reportUrl = `https://${host}/mentorship/parent-report.html?token=${encodeURIComponent(link.access_token)}`;

    let emailSent = false;
    if (parentEmail && process.env.RESEND_API_KEY) {
      const { data: { user: student } } = await admin.auth.admin.getUserById(studentId);
      const studentName = student?.user_metadata?.full_name || student?.user_metadata?.name || 'Your child';
      try {
        const resend = new Resend(process.env.RESEND_API_KEY);
        const { error: sendErr } = await resend.emails.send({
          from: 'Inspire Mentorship <noreply@inspireacademic.org>',
          to: parentEmail,
          subject: `${studentName}'s Vocation & Life Pathways Report`,
          html: `
<!DOCTYPE html>
<html>
<head>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Arial, sans-serif; line-height: 1.6; color: #333; }
    .container { max-width: 600px; margin: 0 auto; padding: 20px; }
    .header { background: #0A1628; color: white; padding: 24px 20px; border-radius: 8px 8px 0 0; }
    .content { background: #fff; padding: 24px 20px; border: 1px solid #eee; border-top: none; border-radius: 0 0 8px 8px; }
    .btn { display: inline-block; background: #B85C1A; color: #fff !important; text-decoration: none; padding: 12px 24px; border-radius: 8px; font-weight: 700; margin: 16px 0; }
    .meta { color: #666; font-size: 13px; }
  </style>
</head>
<body>
  <div class="container">
    <div class="header"><div style="font-size:20px; font-weight:700">Inspire Mentorship</div></div>
    <div class="content">
      <p>Hello,</p>
      <p><strong>${(studentName || '').replace(/</g, '&lt;')}</strong> is working through Inspire Mentorship's Vocation &amp; Life Pathways programme — a guided process of discovering strengths, exploring possible futures, testing assumptions and building a credible pathway into adulthood.</p>
      <p>This link always shows the current state of their journey, including any notes their mentor has chosen to share with you.</p>
      <p style="text-align:center"><a class="btn" href="${reportUrl}">View ${(studentName || 'their').replace(/</g, '&lt;')}'s Report</a></p>
      <p class="meta">This link does not require an account or password. Keep it private.</p>
    </div>
  </div>
</body>
</html>
          `,
        });
        emailSent = !sendErr;
      } catch (emailErr) {
        console.warn('vocation-parent-link email send failed:', emailErr);
      }
    }

    return { statusCode: 200, body: JSON.stringify({ token: link.access_token, url: reportUrl, emailSent }) };
  } catch (error) {
    console.error('vocation-parent-link failed:', error);
    return { statusCode: 500, body: JSON.stringify({ error: error.message }) };
  }
};
