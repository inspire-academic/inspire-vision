// Generates supabase/children_service_seed_phase1.sql from the lesson JSON
// files, so the database copy of a lesson can never drift from the file
// people edit. Re-run after changing any lesson:
//   node faith/children-service/content/build-seed-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const lessonsDir = path.join(here, 'lessons');
const outFile = path.join(here, '..', '..', '..', 'supabase', 'children_service_seed_phase1.sql');

const lessons = fs.readdirSync(lessonsDir).filter((f) => f.endsWith('.json')).sort();
const tag = 'lesson_json';
const sqlText = (s) => `'${String(s).replace(/'/g, "''")}'`;

let sql = `-- ============================================
-- INSPIRE CHILDREN'S SERVICE — Phase 1 seed
-- GENERATED by faith/children-service/content/build-seed-sql.mjs — do not
-- hand-edit; change the lesson JSON and regenerate.
-- Run in Supabase SQL Editor AFTER children_service_schema.sql and
-- children_service_schema_v2_phase1.sql. Safe to re-run.
--
-- Creates: the first church ('inspire'), its two classes, and the lesson
-- rows. It does NOT create people or sessions — those need real user ids
-- and times; see the templates at the bottom.
-- ============================================

INSERT INTO children_service.churches (slug, name, open_enrolment)
VALUES ('inspire', 'Inspire (our own church)', true)
ON CONFLICT (slug) DO NOTHING;

INSERT INTO children_service.classes (church_id, name, age_band)
SELECT c.id, v.name, v.band
FROM children_service.churches c
CROSS JOIN (VALUES ('Explorers (5-7)', 'explorer'), ('Trailblazers (8-11)', 'trailblazer')) AS v(name, band)
WHERE c.slug = 'inspire'
  AND NOT EXISTS (SELECT 1 FROM children_service.classes k WHERE k.church_id = c.id AND k.age_band = v.band);
`;

for (const file of lessons) {
  const raw = fs.readFileSync(path.join(lessonsDir, file), 'utf8');
  const lesson = JSON.parse(raw);
  if (raw.includes(`$${tag}$`)) throw new Error(`${file} contains the dollar-quote tag`);
  sql += `
-- ${file}
INSERT INTO children_service.lessons (church_id, slug, character_name, series_key, sequence, translation, content, status)
VALUES (NULL, ${sqlText(lesson.id)}, ${sqlText(lesson.character.name)}, 'bible-characters', ${lessons.indexOf(file) + 1},${sqlText(lesson.translation.id)},
$${tag}$${JSON.stringify(lesson)}$${tag}$::jsonb, 'published')
ON CONFLICT (COALESCE(church_id, '00000000-0000-0000-0000-000000000000'::uuid), slug)
DO UPDATE SET content = EXCLUDED.content, character_name = EXCLUDED.character_name,
              translation = EXCLUDED.translation, status = EXCLUDED.status, updated_at = now();
`;
}

sql += `
-- ============================================
-- BY HAND, after you have signed up through /faith/children-service/parent/join.html
-- (each step needs values only you have).
--
-- 1. Make yourself church admin (find your id in Authentication > Users):
--    INSERT INTO children_service.church_members (church_id, user_id, role, status, display_name)
--    SELECT id, '<YOUR auth.users id>', 'church_admin', 'active', '<first name>'
--    FROM children_service.churches WHERE slug = 'inspire';
--    Repeat with role 'safeguarding_lead' for the named lead. Record
--    dbs_checked_on / safeguarding_trained_on ONLY when genuinely done:
--    until both dates are set that person cannot see any child.
--
-- 2. Approve a parent who asked to join:
--    UPDATE children_service.church_members SET status = 'active'
--    WHERE user_id = '<parent auth id>' AND role = 'parent';
--
-- 3. A class session (times are UTC), then its Zoom details:
--    WITH s AS (
--      INSERT INTO children_service.sessions (church_id, class_id, lesson_id, starts_at, duration_min, platform)
--      SELECT c.id, k.id, l.id, '2026-10-03 10:00+00', 28, 'zoom'
--      FROM children_service.churches c
--      JOIN children_service.classes k ON k.church_id = c.id AND k.age_band = 'explorer'
--      JOIN children_service.lessons l ON l.slug = 'david-01' AND l.church_id IS NULL
--      WHERE c.slug = 'inspire' RETURNING id)
--    INSERT INTO children_service.session_join_details (session_id, join_url, meeting_id, passcode)
--    SELECT id, 'https://zoom.us/j/<meeting id>?pwd=<...>', '<meeting id>', '<passcode>' FROM s;
--    (join_url must start with https:// — the join page refuses anything else.)
-- ============================================

NOTIFY pgrst, 'reload schema';
`;

fs.writeFileSync(outFile, sql);
console.log(`wrote ${path.relative(process.cwd(), outFile)} (${lessons.length} lesson${lessons.length === 1 ? '' : 's'})`);
